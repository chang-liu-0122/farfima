test_that("plot draws the forecasts in every layout", {
  fit = farfima(X[, 1:100], X[, 101:130], d = 0.3, order = c(1, 0), h = 3, trim = 20, verbose = FALSE)
  fc = predict(fit, verbose = FALSE)
  fc2 = predict(fit, test = X[, 131:160], verbose = FALSE)
  grDevices::pdf(NULL)
  expect_silent(plot(fc2, h = 2, target_test_curve = 5))
  expect_silent(plot(fc2, h = 3))
  expect_silent(plot(fc2, type = "horizons"))
  expect_silent(plot(fc2, type = "horizons", h = c(1, 3)))
  expect_silent(plot(fc2, type = "horizons", h = 1, band = "SR"))
  expect_silent(plot(fc2, type = "horizons", band = c("SR", "AC")))
  expect_silent(plot(fc, type = "horizons"))
  expect_silent(plot(fc2, type = "series", at = c(1, 11, 21)))
  expect_silent(plot(fc2, type = "series", at = 1, xlim = c(120, 165)))
  expect_silent(plot(fc2, type = "recent", n_recent = 10))
  expect_silent(plot(fc2, type = "recent", h = 2))
  expect_silent(plot(fc2, type = "recent", h = c(1, 3)))
  grDevices::dev.off()
  expect_error(plot(fc2, h = 3, target_test_curve = 2), "must be between 3 and 30")
  expect_error(plot(fc2, type = "series", at = 0.5), "values of the grid")
  expect_error(plot(fc2, type = "recent", h = 4), "between 1 and 3")
})
